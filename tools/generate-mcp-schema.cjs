#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const repoRoot = path.resolve(__dirname, '..');
const mcpToolNames = [
  'query_types',
  'query_rules',
  'query_cwt_schema',
  'search_rule_capabilities',
  'explain_scope',
  'parse_pdx_fragment',
  'query_scope',
  'get_diagnostics',
  'analyze_diagnostic_error',
  'query_project_profile',
  'query_project_knowledge',
  'query_workspace_index',
  'explore_pdx_project',
  'query_localisation_index',
  'get_pdx_block',
  'get_completion_at',
  'document_symbols',
  'workspace_symbols',
  'query_definition',
  'query_definition_by_name',
  'query_references',
  'query_scripted_effects',
  'query_scripted_triggers',
  'query_enums',
  'query_static_modifiers',
  'query_variables',
  'get_entity_info',
];

require.extensions['.ts'] = function loadTypeScript(module, filename) {
  const source = fs.readFileSync(filename, 'utf8');
  const output = ts.transpileModule(source, {
    compilerOptions: {
      esModuleInterop: true,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.NodeJs,
      resolveJsonModule: true,
      target: ts.ScriptTarget.ES2020,
    },
    fileName: filename,
  }).outputText;
  module._compile(output, filename);
};

const definitionsPath = path.join(repoRoot, 'client', 'extension', 'ai', 'tools', 'definitions.ts');
const registryPath = path.join(repoRoot, 'client', 'extension', 'ai', 'tools', 'registry.ts');
const { TOOL_DEFINITIONS } = require(definitionsPath);
const { TOOL_REGISTRY } = require(registryPath);

const definitions = new Map(TOOL_DEFINITIONS.map((definition) => [definition.function.name, definition]));
const generated = mcpToolNames.map((name) => {
  const definition = definitions.get(name);
  if (!definition) {
    throw new Error(`Missing upstream tool definition for ${name}`);
  }
  const registry = TOOL_REGISTRY.get(name);
  if (!registry) {
    throw new Error(`Missing upstream tool registry entry for ${name}`);
  }
  return {
    tool: {
      name: definition.function.name,
      description: definition.function.description,
      inputSchema: definition.function.parameters,
    },
    registry: {
      name,
      isWrite: registry.isWrite,
      isReadOnly: registry.isReadOnly,
      effect: registry.effect,
      riskLevel: registry.riskLevel,
      concurrencyClass: registry.concurrencyClass,
    },
  };
});

const targetPath = path.join(repoRoot, 'packages', 'cwtools-shared', 'src', 'generated', 'mcpTools.ts');
const body = [
  '// Generated by tools/generate-mcp-schema.cjs from client/extension/ai/tools/definitions.ts and registry.ts.',
  '// Do not edit by hand; run npm run generate:mcp-schema.',
  '',
  "import type { GeneratedMcpTool } from '../tools/schema';",
  '',
  `export const GENERATED_MCP_TOOLS = ${JSON.stringify(generated, null, 2)} as const satisfies readonly GeneratedMcpTool[];`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(targetPath), { recursive: true });
fs.writeFileSync(targetPath, body, 'utf8');
console.log(`Generated ${generated.length} MCP tool schemas at ${path.relative(repoRoot, targetPath).replace(/\\/g, '/')}`);
