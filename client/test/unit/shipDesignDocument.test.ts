import { expect } from 'chai';
import {
    applyShipDesignOperation,
    parseShipDesignDocument,
    ShipDesignDraftSession,
    ShipDesignEditError,
} from '../../extension/shipDesign/designDocument';
import { parseShipDesignRequest } from '../../shared/shipDesignProtocol';

const SOURCE = [
    '# before',
    'ship_design = {',
    '\tname = "NAME_ONE"',
    '\tship_size = corvette',
    '\tcustom_unknown = preserve_me',
    '\tsection = {',
    '\t\ttemplate = "CORVETTE_MID_S3"',
    '\t\tslot = "mid"',
    '\t\t# slot comment',
    '\t\tcomponent = { slot = "SMALL_GUN_01" template = "SMALL_RED_LASER" }',
    '\t}',
    '\trequired_component = "SENSOR_1"',
    '}',
    '',
    '# between',
    'ship_design = {',
    '\tname = "NAME_TWO"',
    '\tship_size = destroyer',
    '}',
    '',
].join('\n');

describe('ship design document', () => {
    it('parses repeated designs, sections, components, and metadata', () => {
        const result = parseShipDesignDocument(SOURCE);
        expect(result.hasSyntaxErrors).to.equal(false);
        expect(result.designs).to.have.length(2);
        const first = result.designs[0];
        expect(first?.name).to.equal('NAME_ONE');
        expect(first?.shipSize).to.equal('corvette');
        expect(first?.sections[0]?.components[0]?.template).to.equal('SMALL_RED_LASER');
        expect(first?.requiredComponents).to.deep.equal(['SENSOR_1']);
        expect(first?.metadata.custom_unknown).to.equal(undefined);
    });

    it('updates one component without reformatting unrelated source', () => {
        const result = applyShipDesignOperation(SOURCE, {
            kind: 'set-component',
            sectionId: 'design:0/section:0',
            slot: 'SMALL_GUN_01',
            template: 'SMALL_BLUE_LASER',
        });
        expect(result.text).to.contain('template = "SMALL_BLUE_LASER"');
        expect(result.text).to.contain('# slot comment');
        expect(result.text).to.contain('custom_unknown = preserve_me');
        expect(result.text).to.contain('# between');
        expect(result.text).to.contain('name = "NAME_TWO"');
        expect(result.text.indexOf('SMALL_RED_LASER')).to.equal(-1);
        expect(parseShipDesignDocument(result.text).designs[0]?.sections[0]?.components[0]?.template)
            .to.equal('SMALL_BLUE_LASER');
    });

    it('adds and removes a component by stable section id and slot', () => {
        const added = applyShipDesignOperation(SOURCE, {
            kind: 'set-component',
            sectionId: 'design:0/section:0',
            slot: 'SMALL_GUN_02',
            template: 'SMALL_BLUE_LASER',
        });
        expect(added.text).to.contain('slot = "SMALL_GUN_02"');
        const parsed = parseShipDesignDocument(added.text);
        expect(parsed.designs[0]?.sections[0]?.components).to.have.length(2);
        const removed = applyShipDesignOperation(added.text, {
            kind: 'set-component',
            sectionId: 'design:0/section:0',
            slot: 'SMALL_GUN_02',
            template: null,
        });
        expect(removed.text).not.to.contain('SMALL_GUN_02');
        expect(removed.text).to.contain('# slot comment');
    });

    it('replaces a generated loadout while preserving metadata and unknown fields', () => {
        const result = applyShipDesignOperation(SOURCE, {
            kind: 'replace-loadout',
            designId: 'design:0',
            autoGenerated: true,
            sections: [{
                slot: 'mid',
                template: 'CORVETTE_MID_S2PD1',
                components: [{ slot: 'SMALL_GUN_01', template: 'SMALL_MASS_DRIVER_1' }],
            }],
            requiredComponents: ['SENSOR_2', 'CORVETTE_FUSION_REACTOR'],
        });
        const parsed = parseShipDesignDocument(result.text);
        const design = parsed.designs[0];
        expect(design?.sections).to.have.length(1);
        expect(design?.sections[0]?.template).to.equal('CORVETTE_MID_S2PD1');
        expect(design?.requiredComponents).to.deep.equal(['SENSOR_2', 'CORVETTE_FUSION_REACTOR']);
        expect(design?.metadata.auto_gen_design).to.equal(true);
        expect(result.text).to.contain('custom_unknown = preserve_me');
        expect(result.text).to.contain('# before');
        expect(result.text).to.contain('# between');
    });

    it('creates, duplicates, and deletes a design without touching its sibling', () => {
        const created = applyShipDesignOperation(SOURCE, {
            kind: 'create-design',
            name: 'NAME_THREE',
            shipSize: 'cruiser',
            graphicalCulture: 'humanoid_01',
        });
        expect(parseShipDesignDocument(created.text).designs).to.have.length(3);
        const duplicated = applyShipDesignOperation(created.text, {
            kind: 'duplicate-design',
            designId: 'design:2',
            newName: 'NAME_FOUR',
        });
        expect(parseShipDesignDocument(duplicated.text).designs.map(design => design.name))
            .to.deep.equal(['NAME_ONE', 'NAME_TWO', 'NAME_THREE', 'NAME_FOUR']);
        const deleted = applyShipDesignOperation(duplicated.text, { kind: 'delete-design', designId: 'design:3' });
        expect(parseShipDesignDocument(deleted.text).designs.map(design => design.name))
            .to.deep.equal(['NAME_ONE', 'NAME_TWO', 'NAME_THREE']);
        expect(deleted.text).to.contain('# between');
    });

    it('keeps CRLF when inserting a field', () => {
        const source = SOURCE.replace(/\n/g, '\r\n');
        const result = applyShipDesignOperation(source, {
            kind: 'set-field',
            designId: 'design:0',
            field: 'auto_gen_design',
            value: true,
        });
        expect(result.text).to.contain('auto_gen_design = yes\r\n');
        expect(/(^|[^\r])\n/.test(result.text)).to.equal(false);
    });

    it('allows shared metadata edits but protects growth-stage loadouts', () => {
        const source = [
            'ship_design = {',
            '\tname = "BIO"',
            '\tgrowth_stages = {',
            '\t\t{ ship_size = corvette }',
            '\t\t{ ship_size = destroyer }',
            '\t}',
            '}',
        ].join('\n');
        const parsed = parseShipDesignDocument(source);
        expect(parsed.designs[0]?.growthStageCount).to.equal(2);
        expect(parsed.designs[0]?.loadoutReadOnlyReason).to.be.a('string');
        const metadata = applyShipDesignOperation(source, {
            kind: 'set-field',
            designId: 'design:0',
            field: 'is_event_design',
            value: true,
        });
        expect(metadata.text).to.contain('growth_stages = {');
        expect(() => applyShipDesignOperation(source, {
            kind: 'set-component',
            sectionId: 'design:0/section:0',
            slot: 'X',
            template: 'Y',
        })).to.throw(ShipDesignEditError);
    });

    it('rejects malformed syntax and ambiguous duplicate slots', () => {
        expect(() => applyShipDesignOperation('ship_design = { name = "BROKEN"', {
            kind: 'set-field',
            designId: 'design:0',
            field: 'is_event_design',
            value: true,
        })).to.throw(ShipDesignEditError).with.property('code', 'syntax-error');

        const duplicate = SOURCE.replace(
            '\t}\n\trequired_component = "SENSOR_1"',
            '\t\tcomponent = { slot = "SMALL_GUN_01" template = "OTHER" }\n\t}\n\trequired_component = "SENSOR_1"',
        );
        expect(() => applyShipDesignOperation(duplicate, {
            kind: 'set-component',
            sectionId: 'design:0/section:0',
            slot: 'SMALL_GUN_01',
            template: 'NEW',
        })).to.throw(ShipDesignEditError).with.property('code', 'ambiguous-slot');
    });

    it('validates operation payloads at the Webview boundary', () => {
        const valid = parseShipDesignRequest({
            type: 'apply-operation',
            expectedVersion: 3,
            operation: {
                kind: 'set-component',
                sectionId: 'design:0/section:0',
                slot: 'SMALL_GUN_01',
                template: 'SMALL_RED_LASER',
            },
        });
        expect(valid?.type).to.equal('apply-operation');
        expect(parseShipDesignRequest({
            type: 'apply-operation', expectedVersion: 3,
            operation: { kind: 'drop-component', sectionId: 'design:0/section:0', slot: 'SMALL_GUN_01', template: 'SMALL_RED_LASER' },
        })?.type).to.equal('apply-operation');
        expect(parseShipDesignRequest({
            type: 'apply-operation', expectedVersion: 3,
            operation: { kind: 'drop-component', sectionId: 'design:0/section:0', slot: 'SMALL_GUN_01', template: null },
        })).to.equal(null);
        expect(parseShipDesignRequest({
            type: 'apply-operation', expectedVersion: 3,
            operation: { kind: 'set-required-component', designId: 'design:0', slotId: 'required:set:power_core', template: 'REACTOR' },
        })?.type).to.equal('apply-operation');
        expect(parseShipDesignRequest({ type: 'request-required-candidates', designId: 'design:0' })).to.equal(null);
        expect(parseShipDesignRequest({
            type: 'apply-operation', expectedVersion: 3,
            operation: { kind: 'fill-empty-slots', designId: 'design:0', componentKey: 'X', replaceEquipped: true },
        })?.type).to.equal('apply-operation');
        expect(parseShipDesignRequest({
            type: 'apply-operation', expectedVersion: 3,
            operation: { kind: 'fill-empty-slots', designId: 'design:0', componentKey: 'X', replaceEquipped: 'yes' },
        })).to.equal(null);
        expect(() => applyShipDesignOperation(SOURCE, { kind: 'set-required-component', designId: 'design:0', slotId: 'x', template: 'Y' }))
            .to.throw(ShipDesignEditError).with.property('code', 'host-only-operation');
        expect(parseShipDesignRequest({
            type: 'apply-operation',
            expectedVersion: -1,
            operation: { kind: 'delete-design', designId: 'design:0' },
        })).to.equal(null);
        expect(parseShipDesignRequest({
            type: 'apply-operation',
            expectedVersion: 1,
            operation: { kind: 'set-field', designId: 'design:0', field: 'auto_gen_design', value: 1 },
        })).to.equal(null);
    });

    it('keeps edits and undo history outside the source document until save', () => {
        let sourceDocument = 'ship_design = { name = "ONE" }';
        const draft = new ShipDesignDraftSession(sourceDocument);
        draft.apply('ship_design = { name = "TWO" }');
        expect(sourceDocument).to.equal('ship_design = { name = "ONE" }');
        expect(draft.dirty).to.equal(true);
        expect(draft.canUndo).to.equal(true);
        draft.undo();
        expect(draft.text).to.equal(sourceDocument);
        expect(sourceDocument).to.equal('ship_design = { name = "ONE" }');
        draft.redo();
        expect(draft.text).to.equal('ship_design = { name = "TWO" }');
        sourceDocument = draft.text;
        draft.markSaved();
        expect(draft.dirty).to.equal(false);
        draft.undo();
        expect(draft.dirty).to.equal(true);
        expect(sourceDocument).to.equal('ship_design = { name = "TWO" }');
    });

    it('preserves a dirty draft on external conflicts and only adopts them on discard', () => {
        const draft = new ShipDesignDraftSession('one');
        draft.apply('two');
        expect(draft.externalChange('external')).to.equal(false);
        expect(draft.text).to.equal('two');
        expect(draft.hasConflict).to.equal(true);
        expect(() => draft.apply('three')).to.throw(ShipDesignEditError).with.property('code', 'version-conflict');
        draft.discard('external');
        expect(draft.text).to.equal('external');
        expect(draft.dirty).to.equal(false);
        expect(draft.canUndo).to.equal(false);
        expect(draft.externalChange('next')).to.equal(true);
        expect(draft.text).to.equal('next');
    });
});
