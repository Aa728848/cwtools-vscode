#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const repoRoot = path.resolve(__dirname, '..');
const extensionRoot = path.join(repoRoot, 'client', 'extension');
const targetRoot = path.join(repoRoot, 'submodules', 'cwtools-mcp', 'packages', 'cwtools-shared', 'src', 'generated');

require.extensions['.ts'] = function loadTypeScript(module, filename) {
  const source = fs.readFileSync(filename, 'utf8');
  const output = ts.transpileModule(source, {
    compilerOptions: {
      esModuleInterop: true,
      module: ts.ModuleKind.CommonJS,
      moduleResolution: ts.ModuleResolutionKind.NodeJs,
      target: ts.ScriptTarget.ES2020,
    },
    fileName: filename,
  }).outputText;
  module._compile(output, filename);
};

const { getWorkspaceDetectionProfiles } = require(path.join(extensionRoot, 'workspaceDetectionProfiles.ts'));
const header = [
  '// Generated by tools/generate-mcp-detection.cjs from client/extension.',
  '// Do not edit by hand; run npm run generate:mcp-detection.',
  '',
].join('\n');
const profiles = getWorkspaceDetectionProfiles();
const profileSource = `${header}import type { WorkspaceDetectionProfile } from './workspaceGameDetection';\n\nconst PROFILES: readonly WorkspaceDetectionProfile[] = ${JSON.stringify(profiles, null, 2)};\n\nexport function getWorkspaceDetectionProfiles(): WorkspaceDetectionProfile[] {\n  return PROFILES.map(profile => ({ ...profile, alternativeFolderNames: [...profile.alternativeFolderNames] }));\n}\n`;
const outputs = new Map([
  ['workspaceGameDetection.ts', header + fs.readFileSync(path.join(extensionRoot, 'workspaceGameDetection.ts'), 'utf8').replace(/\r\n/g, '\n')],
  ['workspaceDetectionProfiles.ts', profileSource],
  ['workshopDetection.ts', header + fs.readFileSync(path.join(extensionRoot, 'workshopDetection.ts'), 'utf8').replace(/\r\n/g, '\n')],
]);

if (process.argv.includes('--check')) {
  const stale = [...outputs].filter(([name, body]) => {
    const target = path.join(targetRoot, name);
    return !fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== body;
  });
  if (stale.length > 0) {
    console.error(`MCP workspace detection drift: ${stale.join(', ')}. Run npm run generate:mcp-detection and commit the submodule changes.`);
    process.exitCode = 1;
  } else {
    console.log(`MCP workspace detection is up to date (${outputs.size} files).`);
  }
} else {
  fs.mkdirSync(targetRoot, { recursive: true });
  for (const [name, body] of outputs) {
    fs.writeFileSync(path.join(targetRoot, name), body, 'utf8');
  }
  console.log(`Generated ${outputs.size} MCP workspace detection files.`);
}
